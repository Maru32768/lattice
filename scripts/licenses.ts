// Writes THIRD_PARTY_LICENSES: the license text of every npm package bundled into the UI (the
// non-dev packages in package-lock.json) and of every Rust crate in the Windows build, which
// cargo-about renders first (see the `licenses` task in mise.toml).
//   node scripts/licenses.ts <cargo-about output>
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const RULE = "-".repeat(79);
/** Packages that ship no license file: the license file of a package by the same author under the same license (package.json). */
const SIBLING: Record<string, string> = { "react-remove-scroll-bar": "react-remove-scroll" };

export interface NpmPackage {
  name: string;
  version: string;
  license: string;
  text: string;
}

/** Production packages, grouped later by identical text. */
export function npmPackages(root: string): NpmPackage[] {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8")) as {
    packages: Record<string, { dev?: boolean; devOptional?: boolean; version: string; license: string }>;
  };
  return Object.entries(lock.packages)
    .filter(([path, p]) => path.startsWith("node_modules/") && !p.dev && !p.devOptional)
    .map(([path, p]) => {
      const name = path.slice("node_modules/".length);
      const dir = join(root, SIBLING[name] ? `node_modules/${SIBLING[name]}` : path);
      // LICENSE, LICENSE.txt, or one file per license of a dual license (LICENSE-MIT, LICENSE-APACHE-2.0).
      const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^licen[cs]e(-[\w.-]+)?(\.(md|txt))?$/i.test(f)) : [];
      if (!files.length) {
        throw new Error(`no license file in ${path}; run npm install, or add the text by hand`);
      }
      const text = files.map((f) => readFileSync(join(dir, f), "utf8").trim()).join("\n\n");
      return { name, version: p.version, license: p.license, text };
    });
}

export function renderNpm(packages: NpmPackage[]): string {
  const groups = new Map<string, NpmPackage[]>();
  for (const p of packages) {
    groups.set(p.text, [...(groups.get(p.text) ?? []), p]);
  }
  return [...groups].map(([text, ps]) => [RULE, ps[0].license, "Used by:", ...ps.map((p) => `  ${p.name} ${p.version}`), "", text].join("\n")).join("\n\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rust = process.argv[2];
  if (!rust) {
    console.error("usage: node scripts/licenses.ts <cargo-about output>");
    process.exit(1);
  }
  const out = [
    "Lattice third-party licenses",
    "",
    "Generated by `mise run licenses` from package-lock.json and Cargo.lock. Do not edit by hand.",
    "See THIRD_PARTY_NOTICES.md for adapted code, fonts and other notices.",
    "",
    "=".repeat(79),
    "npm packages bundled into the app UI",
    "=".repeat(79),
    "",
    renderNpm(npmPackages(ROOT)),
    "",
    "=".repeat(79),
    "Rust crates compiled into the app",
    "=".repeat(79),
    "",
    readFileSync(rust, "utf8").trim(),
    "",
  ].join("\n");
  writeFileSync(join(ROOT, "THIRD_PARTY_LICENSES"), out.replace(/\r\n/g, "\n"));
  console.log("wrote THIRD_PARTY_LICENSES");
}
