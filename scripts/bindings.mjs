import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DIR = join(ROOT, "src", "bindings");
const temp = mkdtempSync(join(tmpdir(), "lattice-bindings-"));
const generated = join(temp, "bindings");

try {
  const result = spawnSync("cargo", ["test", "--workspace", "--lib", "--quiet", "export_bindings"], {
    cwd: ROOT,
    env: { ...process.env, TS_RS_EXPORT_DIR: generated },
    stdio: "inherit",
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exitCode = result.status ?? 1;
  } else {
    const files = readdirSync(generated).sort();
    const types = files.filter((file) => file.endsWith(".ts")).map((file) => file.slice(0, -3));
    writeFileSync(
      join(generated, "index.ts"),
      `// Generated by scripts/bindings.mjs. Do not edit this file manually.\n${types.map((type) => `export type * from "./${type}";\n`).join("")}`,
    );

    if (process.argv.includes("--check")) {
      const existing = existsSync(DIR) ? readdirSync(DIR) : [];
      const expected = readdirSync(generated);
      const changed = [...new Set([...existing, ...expected])]
        .filter((file) => !existing.includes(file) || !expected.includes(file) || !readFileSync(join(DIR, file)).equals(readFileSync(join(generated, file))))
        .sort();
      if (changed.length) {
        console.error(`src/bindings is out of date: ${changed.join(", ")}. Run \`mise run bindings\`.`);
        process.exitCode = 1;
      }
    } else {
      rmSync(DIR, { recursive: true, force: true });
      cpSync(generated, DIR, { recursive: true });
    }
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
