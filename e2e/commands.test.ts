import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { handlers } from "./mock.ts";

const api = readFileSync(new URL("../src/api.ts", import.meta.url), "utf8");
const invoked = new Set([...api.matchAll(/invoke(?:<[^(]*>)?\(\s*"([^"]+)"/g)].map((m) => m[1]));
assert.ok(invoked.size > 50, "found the invoke calls");

test("the e2e mock answers exactly the commands src/api.ts invokes", () => {
  const mocked = new Set(Object.keys(handlers));
  assert.deepEqual(
    [...invoked].filter((c) => !mocked.has(c)),
    [],
    "add these to e2e/mock.ts",
  );
  assert.deepEqual(
    [...mocked].filter((c) => !invoked.has(c)),
    [],
    "no longer in src/api.ts: remove from e2e/mock.ts",
  );
});

test("the app may call each command src/api.ts invokes, and a remote page the overlay's alone", () => {
  const tauri = new URL("../src-tauri/", import.meta.url);
  const dir = new URL("capabilities/", tauri);
  const read = (file: string, at: URL): unknown => JSON.parse(readFileSync(new URL(file, at), "utf8"));
  const capability = (file: string) => read(file, dir) as { permissions: string[]; webviews?: string[]; windows?: string[]; remote?: object };
  const granted = (file: string) => capability(file).permissions;
  const { webviews, windows, remote } = capability("default.json");
  // A window's are all the webviews in it, and the main window's are the browser tabs too.
  assert.deepEqual({ webviews, windows, remote }, { webviews: ["main", "doc-*", "chat"], windows: undefined, remote: undefined });
  // Those for a platform are merged into it.
  for (const file of readdirSync(tauri).filter((f) => /^tauri\..*conf\.json5?$|^Tauri\..*toml$/.test(f))) {
    const { app: conf } = read(file, tauri) as { app?: { security?: { capabilities?: unknown } } };
    assert.equal(conf?.security?.capabilities, undefined, `${file}: the folder's are all there are`);
  }
  assert.deepEqual(readdirSync(new URL("permissions/", tauri)), ["autogenerated"], "a permission is one command");
  const app = new Set(granted("default.json"));
  assert.deepEqual(
    [...invoked].filter((c) => !app.has(`allow-${c.replaceAll("_", "-")}`)),
    [],
    "add these to capabilities/default.json",
  );
  for (const file of readdirSync(dir).filter((f) => f !== "default.json")) {
    assert.deepEqual(
      granted(file).filter((p) => !p.startsWith("allow-overlay-")),
      [],
      file,
    );
  }
});
